import sys
from pathlib import Path
import unittest
import numpy as np
from scipy import stats
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'src'))
from pyena.rena import one_way_anova

class ANOVAStability(unittest.TestCase):
    def test_rs_residual_dimension_has_finite_p_value(self):
        a=[-0.008605342184913725, 0.0010374746963589916, -0.17416992879082416, -0.10319492800444943, 0.056262827149706617, -0.13075946261052135, -0.0029270223851324004, -0.17109525361655176, -0.2414023988282399, -0.08088596682434011, 0.25596336203729897, -0.004428192692979165, -0.04593805292915755, -0.14608980701852642, -0.12991401078064438, 0.11944967748606913, 0.020832481688733914, 0.2152703644518803, 0.11422408072433826, 0.1307138021610403, 0.2327308784757491, 0.06135246145797486, -0.014042896623308517, -0.021650931408908995, -0.025849362463999624, 0.09311614683334661]
        b=[0.28524673269919854, -0.13176109249819862, -0.12599816546976164, 0.23519480421723662, -0.06992872582363212, -0.023336048729697505, 0.10300857864433853, -0.17487880251833457, -0.03940868690851702, -0.07008242232467078, 0.13935113704596366, -0.017350794720371376, 0.12337591576950613, 0.07185373433123116, -0.06928547562251179, -0.06089379532621093, 0.04339373592314383, 0.2284142227204772, -0.21086435602968698, 0.04540924267996344, -0.05987962343142524, -0.22158011462804084]
        result=one_way_anova(a,b)
        self.assertTrue(np.isfinite(result['p_value']))
        self.assertGreaterEqual(result['f_statistic'],0)
        self.assertAlmostEqual(result['p_value'],1.,places=12)

    def test_ordinary_anova_matches_reference(self):
        a=[1.,2.,4.,6.];b=[3.,6.,7.,11.,14.]
        result=one_way_anova(a,b);ref=stats.f_oneway(a,b)
        self.assertAlmostEqual(result['f_statistic'],ref.statistic,places=12)
        self.assertAlmostEqual(result['p_value'],ref.pvalue,places=12)

if __name__=='__main__':unittest.main()
